import pptxgen from "pptxgenjs";

export interface PptSlide {
    title: string;
    points: string[];
}

export interface PptData {
    title: string;
    subtitle?: string;
    slides?: PptSlide[];
}

const C = {
    bg: "0D0D0F",
    accent: "7C3AED",
    acLight: "A78BFA",
    white: "FFFFFF",
    sub: "A1A1AA",
    cardBg: "18181B",
    divider: "27272A",
};
const FONT = "Calibri";

const fillBg = (slide: pptxgen.Slide, color = C.bg) => {
    slide.addShape("rect", {
        x: 0,
        y: 0,
        w: "100%",
        h: "100%",
        fill: { color },
        line: { color, width: 0 },
    });
};

const accentStripe = (slide: pptxgen.Slide) => {
    slide.addShape("rect", {
        x: 0,
        y: 0,
        w: 0.12,
        h: "100%",
        fill: { color: C.accent },
        line: { color: C.accent, width: 0 },
    });
};

const addCover = (ppt: pptxgen, data: PptData) => {
    const slide = ppt.addSlide();
    fillBg(slide);

    slide.addShape("ellipse", {
        x: 7.8,
        y: -1.2,
        w: 3.5,
        h: 3.5,
        fill: { color: C.accent, transparency: 75 },
        line: { color: C.accent, width: 0, transparency: 75 },
    });

    slide.addText(data.title || "Presentation", {
        x: 0.8,
        y: 1.8,
        w: 8.4,
        h: 1.2,
        fontSize: 38,
        bold: true,
        color: C.white,
        fontFace: FONT,
        align: "left",
    });

    slide.addShape("rect", {
        x: 0.8,
        y: 3.2,
        w: 1.6,
        h: 0.07,
        fill: { color: C.accent },
        line: { color: C.accent, width: 0 },
    });

    if (data.subtitle) {
        slide.addText(data.subtitle, {
            x: 0.8,
            y: 3.5,
            w: 8.4,
            h: 0.8,
            fontSize: 18,
            color: C.sub,
            fontFace: FONT,
            align: "left",
        });
    }

    slide.addText("Generated by CortexAI", {
        x: 0.8,
        y: 6.5,
        w: 5,
        h: 0.4,
        fontSize: 11,
        color: C.sub,
        fontFace: FONT,
        align: "left",
    });
};

const addContentSlide = (
    ppt: pptxgen,
    title: string,
    points: string[],
    num: number,
    total: number
) => {
    const slide = ppt.addSlide();
    fillBg(slide);
    accentStripe(slide);

    slide.addText(`${num} / ${total}`, {
        x: 8.8,
        y: 0.15,
        w: 1,
        h: 0.3,
        fontSize: 9,
        color: C.sub,
        fontFace: FONT,
        align: "right",
    });

    slide.addText(title || `Slide ${num}`, {
        x: 0.4,
        y: 0.2,
        w: 8.4,
        h: 0.65,
        fontSize: 24,
        bold: true,
        color: C.white,
        fontFace: FONT,
        align: "left",
    });

    slide.addShape("rect", {
        x: 0.4,
        y: 1.0,
        w: 9.2,
        h: 0.03,
        fill: { color: C.divider },
        line: { color: C.divider, width: 0 },
    });

    const rows = (points || []).map((pt) => ({
        text: String(pt),
        options: {
            bullet: { code: "25CF" },
            fontSize: 16,
            color: C.white,
            fontFace: FONT,
            paraSpaceAfter: 8,
        },
    }));

    if (rows.length > 0) {
        slide.addText(rows, {
            x: 0.55,
            y: 1.15,
            w: 9.0,
            h: 5.4,
            valign: "top",
        });
    }

    slide.addText("CortexAI", {
        x: 0,
        y: 6.85,
        w: "100%",
        h: 0.28,
        fontSize: 9,
        color: C.sub,
        fontFace: FONT,
        align: "center",
    });
};

const addThankYou = (ppt: pptxgen) => {
    const slide = ppt.addSlide();
    fillBg(slide);

    slide.addShape("ellipse", {
        x: 3.5,
        y: 1.5,
        w: 3,
        h: 3,
        fill: { color: C.accent, transparency: 82 },
        line: { color: C.accent, width: 0, transparency: 82 },
    });

    slide.addText("Thank You", {
        x: 0,
        y: 2.3,
        w: "100%",
        h: 1.2,
        fontSize: 44,
        bold: true,
        color: C.white,
        fontFace: FONT,
        align: "center",
    });

    slide.addText("Generated by CortexAI", {
        x: 0,
        y: 3.7,
        w: "100%",
        h: 0.5,
        fontSize: 14,
        color: C.sub,
        fontFace: FONT,
        align: "center",
    });
};

export const generatePpt = async (data: PptData) => {
    const ppt = new pptxgen();

    ppt.layout = "LAYOUT_WIDE";
    ppt.author = "CortexAI";
    ppt.title = data.title || "Presentation";
    ppt.subject = data.title || "Presentation";
    ppt.company = "CortexAI";
    ppt.theme = { headFontFace: FONT, bodyFontFace: FONT };

    addCover(ppt, data);

    const slides = data?.slides || [];
    slides.forEach((s, i) => {
        addContentSlide(ppt, s.title, s.points, i + 1, slides.length);
    });

    addThankYou(ppt);

    return ppt;
};

