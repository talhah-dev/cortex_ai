import PDFDocument from "pdfkit";

export interface PdfData {
    title: string;
    subtitle?: string;
    sections?: Array<{
        heading: string;
        points?: string[];
    }>;
}

export const generatePdf = async (data: PdfData): Promise<Buffer> => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({
            size: "A4",
            margin: 50,
            info: {
                Author: "CortexAI",
                Title: data.title,
                Creator: "CortexAI",
            },
        });

        const chunks: Buffer[] = [];

        doc.on("data", (chunk: Buffer) => chunks.push(chunk));
        doc.on("end", () => resolve(Buffer.concat(chunks)));
        doc.on("error", (err: any) => reject(err));

        // Title
        doc.fontSize(28)
            .fillColor("#111827")
            .text(data.title, { align: "center" });

        if (data.subtitle) {
            doc.moveDown(0.5);
            doc.fontSize(12)
                .fillColor("#6B7280")
                .text(data.subtitle, { align: "center" });
        }

        doc.moveDown(2);

        data?.sections?.forEach((s) => {
            doc.fontSize(18)
                .fillColor("#111827")
                .text(s.heading);

            doc.moveDown(0.5);

            s?.points?.forEach((p) => {
                doc.fontSize(12)
                    .fillColor("#111827")
                    .text("- " + p, { lineGap: 5 });
            });

            doc.moveDown();
        });

        doc.moveDown();

        // Footer
        doc.fontSize(10)
            .fillColor("#9CA3AF")
            .text("Generated by CortexAI", { align: "center" });

        doc.end();
    });
};
